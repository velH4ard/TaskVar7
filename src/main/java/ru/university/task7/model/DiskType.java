package ru.university.task7.model;

public class DiskType {
    private int id;
    private String name;

    public DiskType(int id, String name) {
        this.id = id;
        this.name = name;
    }

    public int getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
}
